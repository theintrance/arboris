"""Writes src/string/named_references.inc from the WHATWG entity table.

    uv run python scripts/gen_named_references.py [--entities entities.json] [--output PATH]

Without --entities the table is downloaded from https://html.spec.whatwg.org/entities.json.
"""

from __future__ import annotations

import argparse
import json
import urllib.request
from fractions import Fraction
from pathlib import Path

ENTITIES_URL = "https://html.spec.whatwg.org/entities.json"
DEFAULT_OUTPUT = Path(__file__).resolve().parents[1] / "src" / "string" / "named_references.inc"


def c_literal(text: str) -> str:
    return '"' + "".join(f"\\x{byte:02x}" for byte in text.encode("utf-8")) + '"'


def table(name: str, entries: list[tuple[str, str]]) -> str:
    rows = "\n".join(f'    {{"{ref}", {c_literal(text)}}},' for ref, text in sorted(entries))
    return f"inline constexpr NamedCharacterReference {name}[] = {{\n{rows}\n}};\n"


def generate(entities: dict[str, dict]) -> str:
    named = [(ref[1:], entry["characters"]) for ref, entry in entities.items() if ref.endswith(";")]
    legacy = [(ref[1:], entry["characters"]) for ref, entry in entities.items() if not ref.endswith(";")]
    growth = max(
        Fraction(len(entry["characters"].encode("utf-8")), len(ref)) for ref, entry in entities.items()
    )
    return (
        "// Generated by scripts/gen_named_references.py from the WHATWG entity table. Do not edit.\n"
        "\n"
        "// The names that end in ';', the whole table but the legacy ones.\n"
        f"{table('kNamedReferences', named)}"
        "\n"
        "// The names that may be written without ';'. Each also appears above with one.\n"
        f"{table('kLegacyReferences', legacy)}"
        "\n"
        "// The most a reference can grow by when decoded, as decoded bytes per source byte.\n"
        f"inline constexpr std::size_t kReferenceGrowthNumerator = {growth.numerator};\n"
        f"inline constexpr std::size_t kReferenceGrowthDenominator = {growth.denominator};\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--entities", type=Path, help="entities.json; downloaded when omitted")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()

    if args.entities:
        raw = args.entities.read_text(encoding="utf-8")
    else:
        with urllib.request.urlopen(ENTITIES_URL) as response:
            raw = response.read().decode("utf-8")

    args.output.write_text(generate(json.loads(raw)), encoding="utf-8")
    print(f"{args.output}: written")


if __name__ == "__main__":
    main()
